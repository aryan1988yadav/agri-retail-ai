export const useTranslation = (lang = 'en') => {
  const t = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return {
    t,
    format: (template, params = {}) => {
      let str = template || '';
      for (const [key, val] of Object.entries(params)) {
        str = str.replace(`{${key}}`, val);
      }
      return str;
    }
  };
};
